// Fires for all group members except the creator. Copy branches by
// templateType so a new intercession reads differently from other
// spiritual practices.
export async function sendNewGroupMomentPush(
  userId: number,
  opts: { groupSlug: string; momentName: string; templateType: string; creatorName: string }
) {
  const verb = (() => {
    switch (opts.templateType) {
      case "intercession": return "is asking your prayers";
      case "fasting":      return "started a fast";
      case "morning-prayer":
      case "evening-prayer":
                           return "started a prayer practice";
      case "contemplative":
                           return "started a contemplative practice";
      default:             return "started a practice";
    }
  })();
  // Intercessions are treated as prayer requests on the client: the
  // recipient should be able to tap the push, land directly on the
  // prayer slideshow, and pray the new intercession without first
  // navigating to a community page.
  // No badge — see sendNewPrayerRequestPush above. The icon count means
  // "practices left today" and is client-owned; sending an unprayed-
  // intercession count here overwrote it with an unrelated number.
  const isIntercession = opts.templateType === "intercession";
  return sendPushToUser(userId, {
    title: opts.momentName || "Phoebe",
    body: `${opts.creatorName} ${verb}.`,
    path: isIntercession ? `/prayer-mode` : `/communities/${opts.groupSlug}`,
    threadId: `group-moment-${opts.groupSlug}`,
    sound: PHOEBE_SOUND_MID,
  });
}

// Concurrency-limited fan-out of the new-group-practice push. Each recipient's
// intercession badge is computed individually (getUnprayedCount is per-user), so
// publishing one intercession in a large community used to fire hundreds of
// garden COUNT queries + push pipelines AT ONCE (the caller looped with no
// bound) → pool/CPU spike. Cap concurrency like sendPushToUsers.
export async function sendNewGroupMomentPushToMany(
  userIds: number[],
  opts: { groupSlug: string; momentName: string; templateType: string; creatorName: string },
): Promise<void> {
  const unique = Array.from(new Set(userIds.filter(id => Number.isFinite(id))));
  await mapLimit(unique, PUSH_FANOUT_CONCURRENCY, (uid) =>
    sendNewGroupMomentPush(uid, opts).then(() => undefined).catch((err) => {
      logger.warn({ err, uid }, "[push] group moment push failed");
    }));
}

// First-ever amen on a brand-new prayer request — the moment the
// owner's ask stops being theirs alone. Names the first pray-er so the
// owner sees who started carrying it. Fires exactly once per request,
// gated server-side. The collapse-id makes that exactness idempotent
// against any race.
//
// Deep-links to the prayer-request detail slide (not the manage feed),
// so tapping the push lands the owner on a slide-styled view of the
// request itself: the prayer text, the avatar of who said amen, the
// running amen count, and any words of comfort that have been left.
// The earlier `/prayer-list` destination buried that context behind
// another tap.
export function sendFirstAmenPush(
  recipientUserId: number,
  opts: {
    prayerRequestId: number;
    prayerName: string;
    /** Set to the amen-er's user id when they ALREADY left a word of
     *  comfort on this request. The recipient got a word push naming the
     *  same person, so this push MERGES the two: the body covers both,
     *  and the collapse-id reuses the word one so iOS REPLACES that
     *  banner instead of stacking a second notification. */
    withWordFromUserId?: number;
  },
) {
  const firstName = (opts.prayerName || "Someone").split(/\s+/)[0] || "Someone";
  const merged = typeof opts.withWordFromUserId === "number";
  return sendPushToUser(recipientUserId, {
    title: "You've been held in prayer",
    body: merged
      ? `The first amen just went up for your request by ${firstName} — with a word of comfort.`
      : `The first amen just went up for your request by ${firstName}.`,
    // ?amen=1 tells the detail page this is the first-amen landing, so it
    // features the pray-er. Opening the request any other way (e.g. the
    // prayer list) omits the param and shows no single featured amen.
    path: `/prayer-requests/${opts.prayerRequestId}?amen=1`,
    threadId: `prayer-request-${opts.prayerRequestId}`,
    collapseId: merged
      ? prayerWordCollapseId(opts.prayerRequestId, opts.withWordFromUserId as number)
      : firstAmenCollapseId(opts.prayerRequestId),
    sound: PHOEBE_SOUND_HIGH,
  });
}

