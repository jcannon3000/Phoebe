export interface PushPayload {
  title: string;
  body: string;
  // Optional deep-link path that the Capacitor shell routes to on tap.
  // e.g. "/communities/phoebe-architects"
  path?: string;
  // iOS badge number; pass `null` to clear, `undefined` to leave alone.
  badge?: number | null;
  // APNs thread-id for notification grouping. Phoebe uses one thread per
  // "kind" (e.g. "bell", "prayer-request-new", "member-joined").
  threadId?: string;
  // APNs collapse-id — if set, iOS replaces any pending notification
  // with the same ID instead of stacking. Use for events that are
  // idempotent and shouldn't show more than once (e.g. "letter #42
  // arrived" — if the backend somehow sends twice, the second replaces
  // the first rather than showing a duplicate on the lock screen).
  // Max 64 bytes per APNs spec.
  collapseId?: string;
  // Sound name from the app bundle, or "default".
  sound?: string;
  // APNs interruption level. iOS uses this to decide whether the
  // notification breaks through Focus modes / Do Not Disturb:
  //
  //   • "passive"        — silent, never interrupts. For info that
  //                        can wait.
  //   • "active"         — default; uses the user's normal alert
  //                        settings.
  //   • "time-sensitive" — breaks through most Focus modes when the
  //                        user has granted the per-app "Time
  //                        Sensitive Notifications" toggle. Used by
  //                        Duolingo's daily streak reminder so the
  //                        bell still lands during a "Work" or
  //                        "Personal" focus.
  //   • "critical"       — bypasses everything including Do Not
  //                        Disturb; requires a special Apple
  //                        entitlement we don't have.
  //
  // We use "time-sensitive" for the daily bell + evening nudge so a
  // user who's gone heads-down still gets the appointed prompt,
  // matching the Duolingo-style "your streak depends on this" feel.
  interruptionLevel?: "passive" | "active" | "time-sensitive";
  // Arbitrary custom fields merged into the APNs JSON body alongside
  // `path`, and into the web-push JSON. Read by the native shell when
  // filtering delivered notifications for removal. Use this when a
  // group of pushes shares one APNs thread-id (so iOS auto-stacks
  // them on the lock screen) but each push still needs a per-record
  // identifier we can target for individual clearing — e.g. all
  // prayer-request pushes share `thread-id: "prayer-requests"` to
  // stack, but each carries `data.prayerRequestId` so the per-amen
  // sweep can remove only the matching banner.
  data?: Record<string, string | number | boolean>;
  // Silent / background push: no alert, no sound — just `content-available: 1`
  // so the app wakes (best-effort) to act on `data`. Used to REMOVE a delivered
  // notification remotely (e.g. withdraw "Join the breath" when the live count
  // drops below 3). iOS throttles background delivery, so this is best-effort.
  silent?: boolean;
  // Skip web-push subscriptions — send to iOS device tokens only. (A silent push
  // is always iOS-only; this also lets an alert be iOS-scoped.)
  iosOnly?: boolean;
}

interface SendResult {
  attempted: number;
  succeeded: number;
  invalidated: number;
  // Per-transport breakdown. A bare `succeeded > 0` conflates a phone that
  // got the push with a desktop browser that did, which sent a real
  // "reminders are broken" report chasing iOS Focus modes for an hour: the
  // owner's desktop web-push subscription answered while their iPhone's
  // APNs token was dead, and the diagnostic cheerfully said "Sent — check
  // your lock screen." Any surface reporting delivery to a human MUST say
  // WHICH device answered.
  deviceSucceeded: number; // native APNs/FCM tokens
  webSucceeded: number;    // browser web-push subscriptions
}

/**
 * Send a push to every active iOS/Android device token belonging to the
 * given user. Invalid tokens are automatically marked with
 * `invalidated_at = now()` so the next cron pass skips them.
 */
export async function sendPushToUser(userId: number, payload: PushPayload): Promise<SendResult> {
  // Master notifications switch (Settings → Notifications). Every push
  // passes through this function, so one flag here silences all of them
  // — the bell, reminders, digests, prayer-for-you, words of comfort —
  // regardless of device tokens or OS permission. `=== false` so a null
  // (legacy) or true value still sends.
  const [pref] = await db
    .select({ pushEnabled: usersTable.pushEnabled })
    .from(usersTable)
    .where(eq(usersTable.id, userId));
  if (pref?.pushEnabled === false) {
    return { attempted: 0, succeeded: 0, invalidated: 0, deviceSucceeded: 0, webSucceeded: 0 };
  }

  // Centralized emoji strip + title cap — every push goes through this
  // function, so sanitizing here means callers can pass moment / community
  // names with emoji (stripped) and over-long titles (truncated to fit
  // iOS's single line) and we still ship a clean lock-screen string.
  payload = { ...payload, title: truncateTitle(clean(payload.title)), body: clean(payload.body) };
  const [tokens, webSubs] = await Promise.all([
    db.select({
      id: deviceTokensTable.id,
      platform: deviceTokensTable.platform,
      token: deviceTokensTable.token,
    })
      .from(deviceTokensTable)
      .where(and(
        eq(deviceTokensTable.userId, userId),
        isNull(deviceTokensTable.invalidatedAt),
      )),
    db.select({
      id: webPushSubscriptionsTable.id,
      endpoint: webPushSubscriptionsTable.endpoint,
      p256dh: webPushSubscriptionsTable.p256dh,
      auth: webPushSubscriptionsTable.auth,
    })
      .from(webPushSubscriptionsTable)
      .where(and(
        eq(webPushSubscriptionsTable.userId, userId),
        isNull(webPushSubscriptionsTable.invalidatedAt),
      )),
  ]);

  // Silent + iOS-only pushes never go to the web (no service-worker silent path,
  // and a titleless web push would spawn a junk banner).
  const targetWebSubs = (payload.silent || payload.iosOnly) ? [] : webSubs;
  const totalTargets = tokens.length + targetWebSubs.length;
  if (totalTargets === 0) {
    // Two distinct "no tokens" cases worth separating in the log so we
    // can triage silenced users from Railway without a DB session:
    //   1. The user has NEVER registered (zero rows ever inserted).
    //      Usually means push permission denied, or device-token POST
    //      failed on first launch and never retried.
    //   2. The user HAS registered but every row is invalidated_at != NULL
    //      (APNs returned 410 / BadDeviceToken at some point). They
    //      need to reopen the app on iOS 3.3+ to trigger the on-resume
    //      re-register flow. Pre-3.3 bundles stay silenced forever.
    let stoneStateRow: { ever: number; live: number } | null = null;
    try {
      const counts = await db.execute<{ ever: number; live: number }>(sql`
        SELECT
          (SELECT COUNT(*)::int FROM device_tokens WHERE user_id = ${userId}) AS ever,
          (SELECT COUNT(*)::int FROM device_tokens WHERE user_id = ${userId} AND invalidated_at IS NULL) AS live
      `);
      stoneStateRow = (counts.rows?.[0] as { ever: number; live: number } | undefined) ?? null;
    } catch { /* diagnostic only — non-fatal */ }
    const everCount = stoneStateRow?.ever ?? 0;
    const liveCount = stoneStateRow?.live ?? 0;
    // Identify by userId + the static notification "kind" (threadId), never by
    // email or the rendered title (which can carry a name or content).
    logger.info(
      {
        userId,
        kind: payload.threadId ?? "generic",
        deviceTokensEver: everCount,
        deviceTokensLive: liveCount,
        reason:
          everCount === 0
            ? "never-registered"
            : liveCount === 0
              ? "all-invalidated"
              : "unknown",
      },
      "[push] no active device tokens or web subs — skipping send"
    );
    return { attempted: 0, succeeded: 0, invalidated: 0, deviceSucceeded: 0, webSucceeded: 0 };
  }
  logger.info(
    { userId, tokenCount: tokens.length, webSubCount: webSubs.length, kind: payload.threadId ?? "generic" },
    "[push] sending"
  );

  const result: SendResult = {
    attempted: totalTargets, succeeded: 0, invalidated: 0,
    deviceSucceeded: 0, webSucceeded: 0,
  };
  const invalidTokenIds: number[] = [];
  const invalidWebSubIds: number[] = [];

  for (const t of tokens) {
    // Route by the platform the device registered with. Anything unrecognised
    // is skipped rather than assumed to be Apple — sending an Android token to
    // APNs just burns a request and then retires a perfectly good row.
    const send = t.platform === "ios" ? sendOneApns
      : t.platform === "android" ? sendOneFcm
      : null;
    if (!send) continue;
    // One retry on transient errors (5xx or network blip). APNs returns
    // 200 on success, 410/400-BadDeviceToken on invalid token (no point
    // retrying), and 5xx on its own infrastructure trouble. Without the
    // retry every 5xx silently lost a push — Apple's SLA is good but
    // not perfect, and Phoebe's tiny volume means even one drop is a
    // visible "I didn't get the notification" complaint. FCM behaves the
    // same way, so it shares the loop.
    let outcome = await send(t.token, payload);
    if (outcome === "error") {
      await new Promise(r => setTimeout(r, 800));
      outcome = await send(t.token, payload);
    }
    if (outcome === "ok") { result.succeeded += 1; result.deviceSucceeded += 1; }
    else if (outcome === "invalid") invalidTokenIds.push(t.id);
  }

  for (const sub of targetWebSubs) {
    // Same retry pattern for web push. webpush.sendNotification returns
    // an Error subclass with statusCode on 4xx/5xx; sendOneWebPush
    // collapses that to "ok" / "invalid" / "error".
    let outcome = await sendOneWebPush(sub, payload);
    if (outcome === "error") {
      await new Promise(r => setTimeout(r, 800));
      outcome = await sendOneWebPush(sub, payload);
    }
    if (outcome === "ok") { result.succeeded += 1; result.webSucceeded += 1; }
    else if (outcome === "invalid") invalidWebSubIds.push(sub.id);
  }

  if (invalidTokenIds.length > 0) {
    await db.update(deviceTokensTable)
      .set({ invalidatedAt: sql`now()` })
      .where(inArray(deviceTokensTable.id, invalidTokenIds));
    result.invalidated += invalidTokenIds.length;
  }
  if (invalidWebSubIds.length > 0) {
    await db.update(webPushSubscriptionsTable)
      .set({ invalidatedAt: sql`now()` })
      .where(inArray(webPushSubscriptionsTable.id, invalidWebSubIds));
    result.invalidated += invalidWebSubIds.length;
  }

  return result;
}

type WebPushOutcome = "ok" | "invalid" | "error" | "stub";

/**
 * Send a single Web Push (VAPID). Returns:
 *   "ok"      — push service accepted (201)
 *   "invalid" — 404/410 (subscription gone — user revoked permission,
 *               cleared site data, or it expired). Caller invalidates.
 *   "error"   — any other failure (5xx, network). Caller retries next tick.
 *   "stub"    — VAPID env vars unset; logged and skipped.
 */
async function sendOneWebPush(
  sub: { endpoint: string; p256dh: string; auth: string },
  payload: PushPayload,
): Promise<WebPushOutcome> {
  if (!VAPID_PUBLIC || !VAPID_PRIVATE) {
    // Log only the non-sensitive shape — never the payload (its title/body can
    // carry a name or message/prayer text).
    logger.info({
      webpush: "stub",
      endpoint: sub.endpoint.slice(0, 40) + "…",
      kind: payload.threadId ?? "generic",
      path: payload.path ?? "/",
      titleLen: payload.title?.length ?? 0,
      bodyLen: payload.body?.length ?? 0,
    }, "[push] VAPID_* env vars not set — would have sent web push");
    return "stub";
  }

  // Service worker reads this JSON in its `push` listener and turns
  // it into a system notification. Keep the field shape stable —
  // the SW depends on it (title, body, path, tag).
  const json = JSON.stringify({
    title: payload.title,
    body: payload.body,
    path: payload.path ?? "/",
    tag: payload.collapseId ?? payload.threadId ?? undefined,
    threadId: payload.threadId ?? undefined,
    // Same merge as the APNs path — keeps web + iOS payloads in sync
    // for downstream consumers that key off custom fields.
    ...(payload.data ?? {}),
  });

  try {
    await webpush.sendNotification(
      {
        endpoint: sub.endpoint,
        keys: { p256dh: sub.p256dh, auth: sub.auth },
      },
      json,
      {
        // TTL controls how long the push service holds the message
        // if the device is offline. 24h matches the daily cadence —
        // an old bell waiting in queue is no longer useful.
        TTL: 60 * 60 * 24,
        // urgency=high mirrors APNs priority=10; the push service
        // delivers immediately even if the device is in deep sleep.
        urgency: "high",
      },
    );
    return "ok";
  } catch (err) {
    const status = (err as { statusCode?: number } | null)?.statusCode;
    if (status === 404 || status === 410) {
      // Subscription expired or user revoked permission — drop it.
      return "invalid";
    }
    logger.warn({ err, status, endpoint: sub.endpoint.slice(0, 40) + "…" }, "[push] web-push send failed");
    return status && status >= 400 && status < 500 ? "invalid" : "error";
  }
}

type ApnsOutcome = "ok" | "invalid" | "error" | "stub";

/**
 * Send a single APNs notification. Returns:
 *   "ok"      — APNs accepted the payload (200)
 *   "invalid" — APNs rejected the token (410 Unregistered or BadDeviceToken)
 *   "error"   — any other failure (5xx, network). Caller should retry
 *               next bell tick; we don't invalidate the token.
 *   "stub"    — credentials not configured; sender logged and skipped.
 */
/** Deliver one push to an Android device over FCM HTTP v1.
 *
 *  Same outcome contract as sendOneApns so the caller's retry/invalidate loop
 *  is identical: "stub" when unconfigured, "invalid" ONLY for a token FCM says
 *  is dead, "error" for anything retryable.
 *
 *  NOTE on invalidation — deliberately narrower than the APNs path. That one
 *  treats every 4xx as a dead token, which means one bad credential can mark
 *  the entire user base's tokens invalid in a single scheduler tick (see the
 *  2026-07-21 notification audit). Here 401/403 (auth), 429 (rate limit) and
 *  5xx are all retryable; only UNREGISTERED, and INVALID_ARGUMENT naming the
 *  registration token, retire a row. */
async function sendOneFcm(deviceToken: string, payload: PushPayload): Promise<ApnsOutcome> {
  if (!FCM.projectId) return "stub";
  const accessToken = await getFcmAccessToken();
  if (!accessToken) {
    logger.info({ kind: payload.threadId ?? "generic" }, "[push] FCM not configured — stubbing android send");
    return "stub";
  }

  // Every value in FCM's `data` map must be a string.
  const data: Record<string, string> = {};
  if (payload.path) data["path"] = payload.path;
  if (payload.threadId) data["thread-id"] = payload.threadId;
  for (const [k, v] of Object.entries(payload.data ?? {})) {
    if (v !== undefined && v !== null) data[k] = String(v);
  }

  // `collapse_key` + `tag` are Android's "replace the previous one" controls,
  // which is what collapseId means. threadId is iOS GROUPING and must NOT be
  // mapped to tag — that would make every notification of a kind replace the
  // last one. It rides in `data` instead, where the shell can read it.
  const message: Record<string, unknown> = payload.silent
    ? {
        token: deviceToken,
        data,
        android: { priority: "high" },
      }
    : {
        token: deviceToken,
        notification: { title: payload.title, body: payload.body },
        data,
        android: {
          priority: "high",
          ...(payload.collapseId ? { collapse_key: payload.collapseId.slice(0, 64) } : {}),
          notification: {
            sound: "default",
            // No explicit channel_id: on API 26+ a named channel must already
            // exist or the notification is dropped silently, and none is
            // created yet. Omitting it lets Android use the app's default
            // channel, which always works. Worth revisiting alongside a proper
            // "Daily prayer" channel once there's a device to test on.
            ...(payload.collapseId ? { tag: payload.collapseId.slice(0, 64) } : {}),
            ...(typeof payload.badge === "number" ? { notification_count: payload.badge } : {}),
          },
        },
      };

  try {
    const res = await fetch(
      `https://fcm.googleapis.com/v1/projects/${encodeURIComponent(FCM.projectId)}/messages:send`,
      {
        method: "POST",
        headers: {
          authorization: `Bearer ${accessToken}`,
          "content-type": "application/json",
        },
        body: JSON.stringify({ message }),
        // The APNs path has no timeout at all, so one half-open socket can
        // stall a whole scheduler run. Don't repeat that here.
        signal: AbortSignal.timeout(10_000),
      },
    );

    if (res.ok) return "ok";

    const text = await res.text().catch(() => "");
    if (res.status === 401 || res.status === 403) {
      // Credentials problem, not a dead device. Drop the cached access token
      // so the next attempt re-mints, and treat it as retryable.
      fcmToken = null;
      logger.warn({ status: res.status }, "[push] FCM auth rejected — token cache cleared");
      return "error";
    }
    if (res.status === 404 || /UNREGISTERED/i.test(text)) return "invalid";
    if (res.status === 400 && /INVALID_ARGUMENT/i.test(text) && /token/i.test(text)) return "invalid";
    logger.warn({ status: res.status, body: text.slice(0, 200) }, "[push] FCM send failed");
    return "error";
  } catch (err) {
    logger.warn({ err }, "[push] FCM send threw");
    return "error";
  }
}

async function sendOneApns(deviceToken: string, payload: PushPayload): Promise<ApnsOutcome> {
  if (!CREDS.keyP8 || !CREDS.keyId || !CREDS.teamId) {
    // Log only the non-sensitive shape — never the payload (its title/body can
    // carry a name or message/prayer text).
    logger.info({
      apns: "stub",
      bundleId: CREDS.bundleId,
      host: APNS_HOST,
      deviceToken: deviceToken.slice(0, 8) + "…",
      kind: payload.threadId ?? "generic",
      path: payload.path ?? "/",
      titleLen: payload.title?.length ?? 0,
      bodyLen: payload.body?.length ?? 0,
    }, "[push] APNS_* env vars not set — would have sent");
    return "stub";
  }

  // APNs accepts an ES256-signed JWT in the Authorization header. The same
  // JWT is valid for up to 1 hour across any number of requests; we cache
  // it module-scope to avoid re-signing on every push.
  let jwt: string;
  try {
    jwt = await getApnsJwt();
  } catch (err) {
    logger.error({ err }, "[push] APNs JWT sign failed");
    return "error";
  }

  // Silent/background push carries only `content-available` — no alert/sound —
  // so the app can act on `data` (e.g. remove a delivered banner) without
  // showing anything. Normal pushes carry the alert + sound + grouping fields.
  const apsPayload: Record<string, unknown> = payload.silent
    ? { "content-available": 1 }
    : {
        alert: { title: payload.title, body: payload.body },
        sound: payload.sound ?? "default",
      };
  if (!payload.silent) {
    if (payload.threadId) apsPayload["thread-id"] = payload.threadId;
    if (payload.badge !== undefined) apsPayload["badge"] = payload.badge;
    if (payload.interruptionLevel) apsPayload["interruption-level"] = payload.interruptionLevel;
  }

  const body = JSON.stringify({
    aps: apsPayload,
    // Custom fields below `aps` — read by the native shell's
    // `pushNotificationActionPerformed` listener to deep-link in-app,
    // and by the clear-notifications matcher to identify which
    // delivered push to remove (see PushPayload.data).
    ...(payload.path ? { path: payload.path } : {}),
    ...(payload.data ?? {}),
  });

  const headers: Record<string, string> = {
    authorization: `bearer ${jwt}`,
    "apns-topic": CREDS.bundleId as string,
    "apns-push-type": payload.silent ? "background" : "alert",
    "apns-priority": payload.silent ? "5" : "10",
    "content-type": "application/json",
  };
  if (payload.collapseId) {
    // APNs limits collapse-id to 64 bytes; truncate defensively.
    headers["apns-collapse-id"] = payload.collapseId.slice(0, 64);
  }

  // APNs requires HTTP/2 — Node's native fetch (undici) only speaks
  // HTTP/1.1, so the previous version failed every send with
  // "fetch failed: Response does not match the HTTP/..." We use the
  // built-in node:http2 module instead. apnsRequest opens a session
  // per call (cheap; no pooling complexity for our low push volume)
  // and returns parsed { status, reason }.
  let result: { status: number; reason: string };
  try {
    result = await apnsRequest(deviceToken, headers, body);
  } catch (err) {
    logger.warn({ err }, "[push] APNs network error");
    return "error";
  }

  if (result.status === 200) return "ok";
  // 410 Gone = Unregistered; 400 + "BadDeviceToken" reason = device
  // token doesn't match environment (sandbox/prod mixup or app
  // uninstall). Both mean we should stop sending to this token.
  if (result.status === 410) return "invalid";

  logger.warn(
    { status: result.status, reason: result.reason, deviceToken: deviceToken.slice(0, 8) + "…" },
    "[push] APNs send failed"
  );

  if (
    result.status === 400 &&
    (result.reason === "BadDeviceToken" || result.reason === "DeviceTokenNotForTopic")
  ) {
    return "invalid";
  }
  // 4xx generally = something about the request is wrong permanently;
  // invalidate so we don't keep retrying. 5xx = transient, retry later.
  return result.status >= 400 && result.status < 500 ? "invalid" : "error";
}

// Open an HTTP/2 session to APNs, send one request, return the response.
// We don't pool sessions — Phoebe's push volume is tiny and the
// per-request session cost (a TLS handshake) is dwarfed by the JWT cache
// hit and the actual notification round-trip. Pooling would force us to
// handle session lifecycle, GOAWAY frames, idle timeouts, etc., for
// negligible benefit. If we ever push thousands per minute, revisit.
async function apnsRequest(
  deviceToken: string,
  headers: Record<string, string>,
  body: string,
): Promise<{ status: number; reason: string }> {
  return new Promise((resolve, reject) => {
    const session = http2.connect(APNS_HOST);
    let settled = false;
    const finish = (resOrErr: { status: number; reason: string } | Error) => {
      if (settled) return;
      settled = true;
      try { session.close(); } catch { /* already closed */ }
      if (resOrErr instanceof Error) reject(resOrErr); else resolve(resOrErr);
    };

    session.on("error", err => finish(err));

    const req = session.request({
      ":method": "POST",
      ":path": `/3/device/${deviceToken}`,
      ...headers,
    });

    let status = 0;
    let bodyChunks = "";
    req.on("response", h => {
      status = Number(h[":status"] ?? 0);
    });
    req.on("error", err => finish(err));
    req.setEncoding("utf8");
    req.on("data", chunk => { bodyChunks += chunk; });
    req.on("end", () => {
      let reason = "";
      if (bodyChunks) {
        try {
          const parsed = JSON.parse(bodyChunks) as { reason?: string };
          reason = parsed.reason ?? bodyChunks;
        } catch {
          reason = bodyChunks;
        }
      }
      finish({ status, reason });
    });

    req.write(body);
    req.end();
  });
}

// ─── APNs JWT caching ──────────────────────────────────────────────────────
// Apple accepts a single ES256-signed JWT for up to 60 minutes per-token.
// Sign once, cache 55 min, resign.
const APNS_JWT_TTL_MS = 55 * 60 * 1000;
let apnsKeyCache: KeyLike | null = null;
let apnsJwtCache: { token: string; expiresAt: number } | null = null;

async function getApnsJwt(): Promise<string> {
  if (apnsJwtCache && apnsJwtCache.expiresAt > Date.now()) {
    return apnsJwtCache.token;
  }
  if (!apnsKeyCache) {
    apnsKeyCache = (await importPKCS8(
      CREDS.keyP8 as string,
      "ES256"
    )) as KeyLike;
  }
  const nowSec = Math.floor(Date.now() / 1000);
  const token = await new SignJWT({})
    .setProtectedHeader({ alg: "ES256", kid: CREDS.keyId as string })
    .setIssuer(CREDS.teamId as string)
    .setIssuedAt(nowSec)
    .sign(apnsKeyCache);
  apnsJwtCache = { token, expiresAt: Date.now() + APNS_JWT_TTL_MS };
  return token;
}

