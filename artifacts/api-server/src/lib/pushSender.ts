// VAPID config for browser Web Push (Android Chrome / Firefox / Edge,
// desktop too). Subject is required by the spec — must be either a
// `mailto:` or `https:` URL identifying the sender, used by push
// services for abuse contact. Falls through silently when unset so
// dev environments without VAPID keys keep working.
const VAPID_PUBLIC = process.env["VAPID_PUBLIC_KEY"] ?? null;
const VAPID_PRIVATE = process.env["VAPID_PRIVATE_KEY"] ?? null;
const VAPID_SUBJECT = process.env["VAPID_SUBJECT"] ?? "mailto:hello@withphoebe.app";
if (VAPID_PUBLIC && VAPID_PRIVATE) {
  webpush.setVapidDetails(VAPID_SUBJECT, VAPID_PUBLIC, VAPID_PRIVATE);
}

const APNS_ENV = (process.env["APNS_ENVIRONMENT"] ?? "production").toLowerCase();
const APNS_HOST = APNS_ENV === "sandbox"
  ? "https://api.sandbox.push.apple.com"
  : "https://api.push.apple.com";

// ── Android push (FCM HTTP v1) ──────────────────────────────────────────────
// Service-account credentials from the Firebase console. Like the APNs and
// VAPID blocks above, everything falls through silently when unset, so a dev
// environment — or production before the Firebase project exists — keeps
// working and simply stubs Android sends.
//
// FCM_PRIVATE_KEY is the service account's PEM. Railway (and most dashboards)
// can't hold real newlines in an env var, so the literal "\n" sequences are
// unescaped here — the same convention used for other PEM-bearing vars.
const FCM = {
  projectId: process.env["FCM_PROJECT_ID"] ?? null,
  clientEmail: process.env["FCM_CLIENT_EMAIL"] ?? null,
  privateKey: (process.env["FCM_PRIVATE_KEY"] ?? "").replace(/\\n/g, "\n") || null,
};

// Google's OAuth2 access token for FCM, cached until shortly before expiry.
// Unlike the APNs JWT cache this is invalidated on an auth failure (see
// sendOneFcm) rather than blindly replayed for the rest of the window.
let fcmToken: { value: string; expiresAt: number } | null = null;

async function getFcmAccessToken(): Promise<string | null> {
  if (!FCM.projectId || !FCM.clientEmail || !FCM.privateKey) return null;
  if (fcmToken && fcmToken.expiresAt > Date.now() + 60_000) return fcmToken.value;
  try {
    const key = await importPKCS8(FCM.privateKey, "RS256");
    const assertion = await new SignJWT({ scope: "https://www.googleapis.com/auth/firebase.messaging" })
      .setProtectedHeader({ alg: "RS256" })
      .setIssuer(FCM.clientEmail)
      .setSubject(FCM.clientEmail)
      .setAudience("https://oauth2.googleapis.com/token")
      .setIssuedAt()
      .setExpirationTime("1h")
      .sign(key);
    const res = await fetch("https://oauth2.googleapis.com/token", {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        grant_type: "urn:ietf:params:oauth:grant-type:jwt-bearer",
        assertion,
      }),
      signal: AbortSignal.timeout(10_000),
    });
    if (!res.ok) {
      logger.warn({ status: res.status }, "[push] FCM token exchange failed");
      return null;
    }
    const json = (await res.json()) as { access_token?: string; expires_in?: number };
    if (!json.access_token) return null;
    fcmToken = {
      value: json.access_token,
      expiresAt: Date.now() + (json.expires_in ?? 3600) * 1000,
    };
    return fcmToken.value;
  } catch (err) {
    logger.warn({ err }, "[push] FCM token exchange threw");
    return null;
  }
}

// Custom notification sounds bundled in the iOS app
// (phoebe-mobile/ios/App/App/PhoebeRising*.caf — generated by
// scripts/build-rising-sound.mjs). The synthesized "rising swell" comes
// in three octave variants so different notification kinds feel
// distinct on the lock screen even when stacked. iOS falls back to the
// system default chime if a referenced .caf isn't bundled, so old
// builds keep working through the rollout.
const PHOEBE_SOUND_LOW = "PhoebeRising-low.caf";    // daily-rhythm pulses (bell, evening nudge)
const PHOEBE_SOUND_MID = "PhoebeRising.caf";        // group / community / letter pulses
const PHOEBE_SOUND_HIGH = "PhoebeRising-high.caf";  // someone-prayed-for-you / amen pulses

// Strip emoji and other pictographic glyphs out of any string before it
// hits a push title or body. The dashboard intentionally leans on
// emojis (🌿 Morning Prayer) but on the lock screen
// they read as visual clutter and break the calm tone we want. Names
// flow through this on the way into the payload so the user never sees
// "🌱 ___" or "🙏🏽 ___" pop up on their phone.
const EMOJI_RE = /[\p{Extended_Pictographic}\p{Emoji_Presentation}\u200D\uFE0F]/gu;
function clean(text: string | null | undefined): string {
  if (!text) return "";
  return text.replace(EMOJI_RE, "").replace(/\s{2,}/g, " ").trim();
}

// iOS renders the notification title on a SINGLE line and hard-crops the
// overflow mid-character ("Praying for the families affec\u2026"). Many of
// Phoebe's titles interpolate unbounded user content \u2014 display names,
// community / intercession / gathering names, even a full custom "how can
// we pray for you?" question \u2014 any of which can sail past what fits. We cap
// the title to a safe width and truncate at a word boundary with an
// ellipsis so the crop is controlled and readable instead of letting iOS
// sever a word. The body still carries the detail.
//
// 40 chars fits one line on standard iPhones. The narrowest devices
// (SE / mini) may still trim a little, but the ellipsis already signals
// "there's more" and nothing meaningful lives only in the title.
const MAX_TITLE_LEN = 40;
function truncateTitle(title: string): string {
  const t = title.trim();
  if (t.length <= MAX_TITLE_LEN) return t;
  // Reserve one slot for the ellipsis, then prefer cutting at the last
  // space so we don't sever a word \u2014 unless that throws away too much
  // (a single very long token), in which case hard-cut at the budget.
  const budget = MAX_TITLE_LEN - 1;
  const slice = t.slice(0, budget);
  const lastSpace = slice.lastIndexOf(" ");
  const cut = lastSpace > budget * 0.6 ? slice.slice(0, lastSpace) : slice;
  return cut.trimEnd() + "\u2026";
}

