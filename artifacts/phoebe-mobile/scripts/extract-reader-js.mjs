// The reader view's script, shared with Android.
//
// Phoebe's reader view — the restyling of a publisher's page in the reader's
// own browser (oremus, SSJE, Nouwen, Day by Day, Sojourners, The Living
// Church) — is written ONCE, as the `readerJS` string literal in
// ios/App/App/BibleWebViewController.swift, where iOS injects it as a
// document-start user script. Android has no way to read a Swift literal, and
// a hand-kept copy would drift the first week (the host list already drifted
// once between two Swift call sites). So this extracts the literal at build
// time and writes it as an Android asset, which ReaderActivity injects the
// same way (WebViewCompat.addDocumentStartJavaScript). One source of truth;
// the Swift file stays it.
//
// Swift multiline string rules applied here: the closing delimiter's
// indentation is stripped from every line, `\\` is a backslash and `\"` a
// quote. Anything else escaped (`\n`, `\u{…}`, `\(…)`) would mean the literal
// has grown a Swift-only construct this copy cannot carry, so it fails the
// build rather than shipping a broken script. The result is syntax-checked
// with `node --check` for the same reason.
//
// Run by `pnpm run cap:sync:android` (package.json); the output is gitignored.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const swiftPath = resolve(here, "../ios/App/App/BibleWebViewController.swift");
const outPath = resolve(here, "../android/app/src/main/assets/phoebe-reader.js");

const swift = readFileSync(swiftPath, "utf8");
const startMarker = 'private static let readerJS = """';
const start = swift.indexOf(startMarker);
if (start < 0) throw new Error(`readerJS literal not found in ${swiftPath}`);
const bodyStart = swift.indexOf("\n", start) + 1;
const closing = /\n( *)"""\s*(\n|$)/g;
closing.lastIndex = bodyStart;
const close = closing.exec(swift);
if (!close) throw new Error("readerJS literal has no closing delimiter");
const indent = close[1].length;
const raw = swift.slice(bodyStart, close.index);

// Unescape left to right; an escape we don't know is a build error.
const unescaped = raw.replace(/\\(.)/gs, (whole, ch) => {
  if (ch === "\\") return "\\";
  if (ch === '"') return '"';
  throw new Error(`readerJS uses a Swift escape this port cannot carry: ${JSON.stringify(whole)}`);
});
const js = unescaped
  .split("\n")
  .map((line) => (line.startsWith(" ".repeat(indent)) ? line.slice(indent) : line.trimStart() === "" ? "" : line))
  .join("\n");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// GENERATED by scripts/extract-reader-js.mjs from ios/App/App/BibleWebViewController.swift (readerJS).\n// Do not edit: change the Swift literal and run pnpm run cap:sync:android.\n${js}\n`,
);
execFileSync(process.execPath, ["--check", outPath], { stdio: "inherit" });
console.log(`[extract-reader-js] ${outPath} (${js.length} chars)`);
